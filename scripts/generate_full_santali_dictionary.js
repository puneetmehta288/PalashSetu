const fs = require('fs');

const d = new Map();

function add(hin, sat) {
  if (Array.isArray(hin)) {
    hin.forEach(h => {
      const k = h.trim();
      if (k) d.set(k, sat.trim());
    });
  } else {
    const k = hin.trim();
    if (k) d.set(k, sat.trim());
  }
}

