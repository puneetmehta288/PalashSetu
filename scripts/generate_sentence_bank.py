# Google Translate (no API key required)
# ─────────────────────────────────────────────────────────────────────────────
def google_translate(text: str, src: str = "hi", dest: str = "sat") -> str:
    """Translate using Google Translate unofficial endpoint."""
    encoded = urllib.parse.quote(text)
    url = (
        f"https://translate.googleapis.com/translate_a/single"
        f"?client=gtx&sl={src}&tl={dest}&dt=t&q={encoded}"
    )
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=10) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    # data[0] is list of [translated_chunk, original_chunk, ...]
    return "".join(chunk[0] for chunk in data[0] if chunk[0])


